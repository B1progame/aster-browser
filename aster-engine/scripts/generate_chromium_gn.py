#!/usr/bin/env python3
import pathlib
import re
import subprocess
import sys
import zipfile


root = pathlib.Path(sys.argv[1])
chromium_src = root.parents[2]
artifacts = []
chromium_provided_artifacts = {
    "androidx.annotation:annotation-experimental",
    "androidx.annotation:annotation-jvm",
    "androidx.arch.core:core-common",
    "androidx.arch.core:core-runtime",
    "androidx.collection:collection-jvm",
    "androidx.concurrent:concurrent-futures",
    "androidx.core:core",
    "androidx.core:core-ktx",
    "androidx.core:core-viewtree",
    "androidx.customview:customview",
    "androidx.exifinterface:exifinterface",
    "androidx.interpolator:interpolator",
    "androidx.lifecycle:lifecycle-livedata-core",
    "androidx.lifecycle:lifecycle-common-jvm",
    "androidx.lifecycle:lifecycle-process",
    "androidx.lifecycle:lifecycle-runtime-android",
    "androidx.lifecycle:lifecycle-viewmodel-android",
    "androidx.loader:loader",
    "androidx.localbroadcastmanager:localbroadcastmanager",
    "androidx.savedstate:savedstate",
    "androidx.startup:startup-runtime",
    "androidx.tracing:tracing",
    "androidx.versionedparcelable:versionedparcelable",
    "androidx.viewpager:viewpager",
    "com.google.android.gms:play-services-base",
    "com.google.android.gms:play-services-basement",
    "com.google.android.gms:play-services-tasks",
    "com.google.errorprone:error_prone_annotations",
    "com.google.guava:failureaccess",
    "com.google.guava:guava",
    "org.jetbrains.kotlinx:kotlinx-coroutines-android",
    "org.jetbrains.kotlinx:kotlinx-coroutines-core-jvm",
    "org.jetbrains.kotlin:kotlin-stdlib",
    "org.jetbrains:annotations",
    "org.jspecify:jspecify",
}
for line in (root / "dependencies.lock").read_text().splitlines():
    coordinate, relpath, extension, _digest = line.split("|", 3)
    if coordinate.rsplit(":", 1)[0] in chromium_provided_artifacts:
        print(f"Using Chromium's dependency instead of staging {coordinate}")
        # LiteRT-LM's Kotlin reflection looks up these runtime metadata files
        # through the class loader. Chromium already provides Kotlin classes,
        # but its stdlib jar does not include the metadata from LiteRT's newer
        # stdlib. Package only the metadata (never duplicate Kotlin classes).
        if coordinate == "org.jetbrains.kotlin:kotlin-stdlib:2.4.20":
            source_jar = root / relpath
            metadata_jar = root / "kotlin-builtins-resources.jar"
            with zipfile.ZipFile(source_jar) as source, zipfile.ZipFile(
                metadata_jar, "w", compression=zipfile.ZIP_DEFLATED
            ) as output:
                for name in source.namelist():
                    if name.endswith(".kotlin_builtins"):
                        output.writestr(name, source.read(name))
            artifacts.append(("aster_kotlin_builtins_resources_jar_java", "kotlin-builtins-resources.jar", "jar"))
        continue
    artifact_path = root / relpath
    if extension == "aar":
        with zipfile.ZipFile(artifact_path) as archive:
            if "classes.jar" not in archive.namelist():
                print(f"Skipping resource-only/empty Android artifact: {coordinate}")
                continue
            with zipfile.ZipFile(archive.open("classes.jar")) as classes:
                if not any(name.endswith(".class") for name in classes.namelist()):
                    print(f"Skipping empty Android artifact: {coordinate}")
                    continue
    else:
        with zipfile.ZipFile(artifact_path) as archive:
            if not any(name.endswith(".class") for name in archive.namelist()):
                print(f"Skipping empty Java artifact: {coordinate}")
                continue
    name = re.sub(r"[^A-Za-z0-9_]", "_", coordinate)
    artifacts.append((name + "_" + extension + "_java", relpath, extension))

aar_targets = [("aster_engine_java", "aster-engine.aar")]
aar_targets += [
    ("aster_dep_" + name, relpath)
    for name, relpath, extension in artifacts
    if extension == "aar"
]
for target, relpath in aar_targets:
    subprocess.run(
        [
            sys.executable,
            str(chromium_src / "build/android/gyp/aar.py"),
            "list",
            "--output",
            str(root / f"{target}.info"),
            str(root / relpath),
        ],
        cwd=chromium_src,
        check=True,
        stdout=subprocess.DEVNULL,
    )

lines = [
    "# Generated by aster-engine/scripts/generate_chromium_gn.py.",
    'import("//build/config/android/rules.gni")',
    "",
    'android_aar_prebuilt("aster_engine_java") {',
    '  aar_path = "runtime/aster-engine.aar"',
    '  info_path = "runtime/aster_engine_java.info"',
    "  ignore_aidl = true",
    "  extract_native_libraries = true",
    "}",
]
deps = [":aster_engine_java"]
for name, relpath, extension in artifacts:
    target = "aster_dep_" + name
    deps.append(":" + target)
    if extension == "aar":
        lines += [
            "",
            f'android_aar_prebuilt("{target}") {{',
            f'  aar_path = "runtime/{relpath}"',
            f'  info_path = "runtime/{target}.info"',
            "  ignore_aidl = true",
            "  extract_native_libraries = true",
            "}",
        ]
    else:
        lines += [
            "",
            f'java_prebuilt("{target}") {{',
            f'  jar_path = "runtime/{relpath}"',
            f'  output_name = "{target}"',
            "  supports_android = true",
            "  requires_android = true",
            "  enable_bytecode_checks = false",
            *(["  include_java_resources = true"] if name == "aster_kotlin_builtins_resources_jar_java" else []),
            "}",
        ]
lines += [
    "",
    'java_group("aster_engine_runtime_java") {',
    "  deps = [",
    *[f'    "{dep}",' for dep in deps],
    "  ]",
    '  visibility = [ "//chrome/android:*" ]',
    "}",
    "",
]
native_aar_libraries = []
seen_native_libraries = set()
for name, relpath, extension in artifacts:
    if extension != "aar":
        continue
    with zipfile.ZipFile(root / relpath) as archive:
        libraries = sorted(
            path for path in archive.namelist()
            if path.startswith("jni/") and path.endswith(".so")
        )
    if not libraries:
        continue
    target = "aster_dep_" + name
    unique_libraries = []
    for path in libraries:
        abi, basename = path.split("/")[1:]
        key = (abi, basename)
        if key in seen_native_libraries:
            print(f"Skipping duplicate AAR native library {path} from {relpath}")
            continue
        seen_native_libraries.add(key)
        unique_libraries.append(path)
    if unique_libraries:
        native_aar_libraries.append((target, unique_libraries))
native_abis = sorted({path.split("/")[1] for _, paths in native_aar_libraries for path in paths})
lines += [
    'group("aster_gecko_native_libraries") {',
    "  deps = [",
    *[f'    ":{target}",' for target, _ in native_aar_libraries],
    "  ]",
]
for abi, cpu in (("x86_64", "x64"), ("arm64-v8a", "arm64")):
    if abi not in native_abis:
        continue
    lines += [
        f'  if (target_cpu == "{cpu}") {{',
        '    metadata = {',
        '      shared_libraries = [',
    ]
    for target, paths in native_aar_libraries:
        lines += [
            f'        "$root_out_dir/obj/third_party/aster/{target}/jni/{abi}/{path.rsplit("/", 1)[1]}",'
            for path in paths
            if path.startswith(f"jni/{abi}/")
        ]
    lines += [
        "      ]",
        "    }",
        "  }",
    ]
lines += ["}", ""]
(root.parent / "BUILD.gn").write_text("\n".join(lines))
native_library_count = sum(len(paths) for _, paths in native_aar_libraries)
print(f"Generated Chromium GN targets for {len(artifacts)} Gecko runtime artifacts and {native_library_count} native libraries")
